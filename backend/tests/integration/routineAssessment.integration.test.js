import {beforeAll,afterAll,it,expect} from 'vitest';
const prisma=require('../../src/database/prisma');
const {routineAssessment}=require('../../src/services/routineAssessment.service');
const users=[];
beforeAll(async()=>{for(let i=0;i<2;i++)users.push((await prisma.user.create({data:{name:'Reavaliação teste',email:`review-context-${Date.now()}-${i}@example.invalid`,passwordHash:'not-used'}})).id)});
afterAll(async()=>{await prisma.user.deleteMany({where:{id:{in:users}}});await prisma.$disconnect()});
it('lê cadastros atuais, identifica ausências e isola cada usuário',async()=>{
 const userId=users[0];
 const routine=await prisma.routineItem.create({data:{userId,name:'Sem horário',type:'Saúde',isActive:true}});
 await prisma.routineItem.create({data:{userId,name:'Rotina inativa',type:'Saúde',isActive:false}});
 await prisma.job.create({data:{userId,name:'Trabalho sem jornada',tasks:{create:{title:'Tarefa atual'}}}});
 const goal=await prisma.goal.create({data:{userId,title:'Estudar',sessions:{create:{date:new Date('2026-01-01'),startTime:'10:00',endTime:'11:00'}}}});
 await prisma.reminder.create({data:{userId,title:'Concluído',reminderTime:'10:00',recurrence:'DAILY',isCompleted:true}});
 await prisma.unexpectedEvent.create({data:{userId,title:'Imprevisto atual',date:new Date('2027-01-10'),startTime:'12:00',endTime:'13:00',priority:'HIGH',status:'PENDING'}});
 const week={weekStart:'2027-01-10',weekEnd:'2027-01-16'};
 const before=await routineAssessment(userId,week);
 expect(before.counts).toMatchObject({routines:2,activeRoutines:1,flexibleRoutines:0,activeJobs:1,tasks:1,activeGoals:1,activeReminders:0,pendingUnexpected:1});
 expect(before.findings.map(row=>row.kind)).toEqual(expect.arrayContaining(['rotinas','trabalho','metas']));
 expect((await routineAssessment(users[1],week)).counts.routines).toBe(0);
 await prisma.routineItem.update({where:{id:routine.id},data:{name:'Renomeada',isFlexible:true,schedules:{create:{dayOfWeek:1,startTime:'07:00',endTime:'08:00'}}}});
 await prisma.goalPlanSession.create({data:{goalId:goal.id,date:new Date('2027-01-11'),startTime:'10:00',endTime:'11:00'}});
 const after=await routineAssessment(userId,{...week,previousInventory:before.inventory});
 expect(after.counts.flexibleRoutines).toBe(1);expect(after.findings.some(row=>row.kind==='rotinas'||row.kind==='metas')).toBe(false);
 expect(after.changes.updated.map(row=>row.title)).toEqual(expect.arrayContaining(['Renomeada','Estudar']));
 expect(after.inventory.some(row=>row.title==='Tarefa atual')).toBe(true);
 const reminder=await prisma.reminder.create({data:{userId,title:'Novo lembrete',reminderTime:'09:00',recurrence:'DAILY'}});
 await prisma.routineItem.delete({where:{id:routine.id}});
 const latest=await routineAssessment(userId,{...week,previousInventory:after.inventory});
 expect(latest.changes.added.map(row=>row.title)).toEqual(['Novo lembrete']);
 expect(latest.changes.removed.map(row=>row.title)).toEqual(['Renomeada']);
 expect(latest.inventoryFingerprint).not.toBe(after.inventoryFingerprint);
 const unchanged=await routineAssessment(userId,{...week,previousInventory:latest.inventory});
 expect(unchanged.changes).toMatchObject({baseline:false,added:[],updated:[],removed:[]});
 expect(unchanged.inventoryFingerprint).toBe(latest.inventoryFingerprint);
 expect(reminder.userId).toBe(userId);
});
