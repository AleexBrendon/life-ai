const { test } = require('node:test');
const assert = require('node:assert/strict');
const { readFileSync, readdirSync } = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');
const { PGLiteSocketServer } = require('@electric-sql/pglite-socket');
const { PrismaClient } = require('@prisma/client');
const { PrismaPg } = require('@prisma/adapter-pg');
const { globalSearch } = require('../../src/services/globalSearch.service');
const { createChangeHistory, hash } = require('../../src/services/changeHistory.service');
const { createRescheduleService } = require('../../src/services/reschedule.service');
const { setActivityStatus } = require('../../src/services/activityStatus.service');

test('productivity features on real isolated PostgreSQL and Prisma transactions', {timeout:90000}, async t=>{
  const memory=new PGlite(),server=new PGLiteSocketServer({db:memory,host:'127.0.0.1',port:0});let db;
  t.after(async()=>{if(db)await db.$disconnect();await server.stop();await memory.close();});
  const migrations=path.resolve(__dirname,'../../prisma/migrations');
  for(const name of readdirSync(migrations).filter(name=>/^\d/.test(name)).sort())await memory.exec(readFileSync(path.join(migrations,name,'migration.sql'),'utf8'));
  await server.start();
  db=new PrismaClient({adapter:new PrismaPg({connectionString:`postgresql://postgres:postgres@${server.getServerConn()}/postgres`,max:1})});
  const createdAt=new Date('2030-01-01T12:00:00Z'),date='2030-01-07';
  const owner=await db.user.create({data:{name:'Owner',email:'productivity@example.invalid',passwordHash:'not-searchable',createdAt}});
  const other=await db.user.create({data:{name:'Other',email:'other@example.invalid',passwordHash:'not-searchable',createdAt}});
  await db.profile.create({data:{userId:owner.id,timezone:'America/Sao_Paulo'}});
  const routine=await db.routineItem.create({data:{userId:owner.id,name:'Projeto leitura',type:'PERSONAL',createdAt,preparationMinutes:15}});
  const slot=await db.routineSchedule.create({data:{routineItemId:routine.id,dayOfWeek:1,startTime:'10:00',endTime:'11:00',createdAt}});
  const goal=await db.goal.create({data:{userId:owner.id,title:'Projeto estudo',createdAt}});
  const session=await db.goalPlanSession.create({data:{goalId:goal.id,date:new Date(date),startTime:'08:00',endTime:'09:00',createdAt}});
  const job=await db.job.create({data:{userId:owner.id,name:'Projeto trabalho',company:'Empresa',createdAt}});
  await db.workSchedule.create({data:{jobId:job.id,dayOfWeek:1,startTime:'14:00',endTime:'15:00',createdAt}});
  await db.jobTask.create({data:{jobId:job.id,title:'Projeto tarefa'}});
  await db.goal.create({data:{userId:other.id,title:'Projeto privado'}});
  await db.reminder.create({data:{userId:owner.id,title:'Projeto lembrete',date:new Date(date),reminderTime:'14:30',recurrence:'NONE',createdAt}});
  await db.financeEntry.create({data:{userId:owner.id,title:'Projeto reserva',kind:'SAVING',amountCents:1000}});
  await db.financeBill.create({data:{userId:owner.id,title:'Projeto conta',amountCents:2000,firstDueDate:new Date(date)}});
  const event=await db.unexpectedEvent.create({data:{userId:owner.id,title:'Projeto evento',date:new Date(date),startTime:'17:00',endTime:'18:00',priority:'LOW',status:'PENDING',createdAt}});
  const history=createChangeHistory(db);
  const now=()=>new Date('2030-01-07T09:00:00Z');
  const scheduling=createRescheduleService(db,{now});
  const input={kind:'metas',sourceId:session.id,date,toDate:date,startTime:'14:00',endTime:'15:00'};

  await t.test('global search merges categories, paginates and never leaks another account',async()=>{
    const first=await globalSearch(db,owner.id,{q:'PROJETO',limit:3});
    assert.equal(first.items.length,3);assert.equal(first.hasMore,true);assert.equal(first.nextOffset,3);
    const all=await globalSearch(db,owner.id,{q:'Projeto',limit:50});
    assert.equal(all.items.length,8);assert.ok(!all.items.some(row=>row.title.includes('privado')));
    assert.equal(new Set(all.items.map(row=>row.type)).size,8);
    const second=await globalSearch(db,owner.id,{q:'Projeto',offset:3,limit:3});
    assert.ok(!second.items.some(row=>first.items.some(old=>old.type===row.type&&old.id===row.id)));
    assert.equal((await globalSearch(db,owner.id,{q:'Projeto',kind:'tarefas'})).items.length,1);
    assert.equal((await globalSearch(db,other.id,{q:'Projeto'})).items.length,1);
    assert.equal((await globalSearch(db,owner.id,{q:'not-searchable'})).items.length,0);
    await assert.rejects(globalSearch(db,owner.id,{q:'x',limit:100}),/./);
    await assert.rejects(globalSearch(db,owner.id,{q:'Projeto',offset:5001}),/./);
  });
  await t.test('wildcards and SQL syntax are literal search data',async()=>{
    await db.goal.create({data:{userId:owner.id,title:'Economia 100%_literal'}});
    assert.equal((await globalSearch(db,owner.id,{q:'%_'})).items.length,1);
    assert.equal((await globalSearch(db,owner.id,{q:"' OR 1=1 --"})).items.length,0);
    assert.equal(hash({a:1,b:{c:2,d:3}}),hash({b:{d:3,c:2},a:1}));
  });
  await t.test('status and audit commit atomically, support undo and idempotent replay',async()=>{
    await db.$transaction(tx=>setActivityStatus({db:tx,userId:owner.id,input:{kind:'rotinas',sourceId:slot.id,date,status:'COMPLETED'}}),{isolationLevel:'Serializable'});
    const change=await db.changeEvent.findFirst({where:{userId:owner.id,action:'ACTIVITY_STATUS'},orderBy:{id:'desc'}});
    assert.equal(change.reversible,true);assert.equal(change.before.row,null);
    await assert.rejects(history.undo(other.id,change.id),/não encontrada/);
    await assert.rejects(history.detail(other.id,change.id),/não encontrada/);
    await history.undo(owner.id,change.id);
    assert.equal(await db.routineExecution.count({where:{userId:owner.id}}),0);
    assert.equal((await history.undo(owner.id,change.id)).alreadyUndone,true);
    assert.equal(await db.changeEvent.count({where:{userId:owner.id,action:'UNDO'}}),1);
  });
  await t.test('undo refuses an intervening edit, including edits outside the new endpoints',async()=>{
    await db.$transaction(tx=>setActivityStatus({db:tx,userId:owner.id,input:{kind:'rotinas',sourceId:slot.id,date,status:'COMPLETED'}}));
    const change=await db.changeEvent.findFirst({where:{action:'ACTIVITY_STATUS'},orderBy:{id:'desc'}});
    await db.routineExecution.updateMany({where:{userId:owner.id},data:{status:'SKIPPED'}});
    await assert.rejects(history.undo(owner.id,change.id),/mudou/);
    await db.routineExecution.deleteMany({where:{userId:owner.id}});
  });
  await t.test('an audit failure rolls back the activity mutation',async()=>{
    const count=await db.changeEvent.count();
    await assert.rejects(db.$transaction(async tx=>{
      const broken=new Proxy(tx,{get(target,key){return key==='changeEvent'?{create:async()=>{throw Error('AUDIT_UNAVAILABLE');}}:Reflect.get(target,key);}});
      await setActivityStatus({db:broken,userId:owner.id,input:{kind:'rotinas',sourceId:slot.id,date,status:'COMPLETED'}});
    }),/AUDIT_UNAVAILABLE/);
    assert.equal(await db.routineExecution.count({where:{userId:owner.id}}),0);
    assert.equal(await db.changeEvent.count(),count);
  });
  await t.test('preview never mutates schedules, finds conflicts and offers free alternatives',async()=>{
    const stage=await scheduling.preview(owner.id,input);
    assert.ok(stage.conflicts.some(row=>row.title==='Projeto trabalho'));
    assert.ok(stage.conflicts.some(row=>row.title==='Projeto lembrete'));
    assert.equal(stage.suggestions.length,3);
    assert.equal((await db.goalPlanSession.findUnique({where:{id:session.id}})).startTime,'08:00');
    await assert.rejects(scheduling.apply(other.id,stage.id,true),/não encontrada/);
    await assert.rejects(scheduling.apply(owner.id,stage.id),/confirme/);
    const applied=await scheduling.apply(owner.id,stage.id,true);
    assert.equal((await db.goalPlanSession.findUnique({where:{id:session.id}})).startTime,'14:00');
    assert.equal((await scheduling.apply(owner.id,stage.id,true)).alreadyApplied,true);
    await history.undo(owner.id,applied.changeId);
    assert.equal((await db.goalPlanSession.findUnique({where:{id:session.id}})).startTime,'08:00');
  });
  await t.test('preparation, touching intervals, stale previews and expiry are enforced',async()=>{
    const preparation=await scheduling.preview(owner.id,{...input,startTime:'09:30',endTime:'10:00'});
    assert.ok(preparation.conflicts.some(row=>row.kind==='rotinas'));
    const adjacent=await scheduling.preview(owner.id,{...input,startTime:'13:00',endTime:'14:00'});
    assert.equal(adjacent.conflicts.length,0);
    await db.unexpectedEvent.update({where:{id:event.id},data:{title:'Nova descrição'}});
    await assert.rejects(scheduling.apply(owner.id,adjacent.id),/agenda mudou/);
    const expired=await scheduling.preview(owner.id,{...input,startTime:'12:00',endTime:'13:00'});
    await db.scheduleChangePreview.update({where:{id:expired.id},data:{expiresAt:new Date('2029-01-01')}});
    await assert.rejects(scheduling.apply(owner.id,expired.id),/expirou/);
  });
  await t.test('one-day routine changes preserve recurring template and undo removes the override',async()=>{
    const stage=await scheduling.preview(owner.id,{kind:'rotinas',sourceId:slot.id,date,toDate:date,startTime:'11:00',endTime:'12:00'});
    const applied=await scheduling.apply(owner.id,stage.id);
    assert.equal((await db.routineSchedule.findUnique({where:{id:slot.id}})).startTime,'10:00');
    assert.equal((await db.routineExecution.findFirst({where:{routineScheduleId:slot.id}})).startTime,'11:00');
    await history.undo(owner.id,applied.changeId);
    assert.equal(await db.routineExecution.count({where:{routineScheduleId:slot.id}}),0);
    await assert.rejects(scheduling.preview(owner.id,{kind:'rotinas',sourceId:slot.id,date,toDate:'2030-01-08',startTime:'11:00',endTime:'12:00'}),/mantêm a data/);
  });
  await t.test('undo does not silently create a conflict in the original time',async()=>{
    const stage=await scheduling.preview(owner.id,{...input,startTime:'12:00',endTime:'13:00'});
    const applied=await scheduling.apply(owner.id,stage.id);
    const blocker=await db.unexpectedEvent.create({data:{userId:owner.id,title:'Novo compromisso',date:new Date(date),startTime:'08:00',endTime:'09:00',priority:'LOW',status:'PENDING'}});
    await assert.rejects(history.undo(owner.id,applied.changeId),/horário anterior/);
    await db.unexpectedEvent.delete({where:{id:blocker.id}});
    await history.undo(owner.id,applied.changeId);
  });
  await t.test('dated sessions move across dates; completed sessions and recurring reminders are protected',async()=>{
    const stage=await scheduling.preview(owner.id,{...input,toDate:'2030-01-08',startTime:'12:00',endTime:'13:00'});
    const applied=await scheduling.apply(owner.id,stage.id);
    assert.equal((await db.goalPlanSession.findUnique({where:{id:session.id}})).date.toISOString().slice(0,10),'2030-01-08');
    await history.undo(owner.id,applied.changeId);
    await db.goalPlanSession.update({where:{id:session.id},data:{status:'COMPLETED'}});
    await assert.rejects(scheduling.preview(owner.id,input),/pendentes/);
    await db.goalPlanSession.update({where:{id:session.id},data:{status:'PENDING'}});
    const reminder=await db.reminder.create({data:{userId:owner.id,title:'Recorrente',reminderTime:'16:00',recurrence:'DAILY',createdAt}});
    await assert.rejects(scheduling.preview(owner.id,{...input,kind:'lembretes',sourceId:reminder.id,startTime:'16:00',endTime:'16:00'}),/recorrente/);
    await assert.rejects(scheduling.preview(owner.id,{...input,sourceId:2147483647}),/não encontrada/);
    await assert.rejects(scheduling.preview(owner.id,{...input,toDate:'2029-01-01'}),/futuro/);
  });
  await t.test('API authentication, validation, planner history and user isolation',async()=>{
    const express=require('express'),request=require('supertest'),jwt=require('jsonwebtoken');
    const prismaPath=require.resolve('../../src/database/prisma'),redisPath=require.resolve('../../src/database/redis');
    require.cache[prismaPath]={id:prismaPath,filename:prismaPath,loaded:true,exports:db};
    require.cache[redisPath]={id:redisPath,filename:redisPath,loaded:true,exports:{get:async()=>null}};
    assert.equal(require('../../src/middlewares/activityNotification.middleware').describe({method:'POST',originalUrl:'/api/productivity/reschedule/preview',user:{id:owner.id},body:input},{success:true,data:{id:'preview'}}),null);
    process.env.JWT_SECRET='isolated-productivity-test-secret';
    const app=express();app.use(express.json());app.use('/api/productivity',require('../../src/routes/productivity.routes'));app.use('/api/planner',require('../../src/routes/planner.routes'));
    const token=jwt.sign({sub:String(owner.id)},process.env.JWT_SECRET,{expiresIn:'1h'});
    const api=(method,url)=>request(app)[method](url).set('Authorization','Bearer '+token);
    assert.equal((await request(app).get('/api/productivity/search?q=Projeto')).status,401);
    assert.equal((await api('get','/api/productivity/search?q=Projeto&limit=100')).status,400);
    assert.equal((await api('get','/api/productivity/search?q=Projeto')).status,200);
    assert.equal((await api('post','/api/productivity/reschedule/no-uuid/apply').send({})).status,400);
    const saved=await api('post','/api/planner/metas').send({title:'Cadastro auditado',sessions:[]});
    assert.equal(saved.status,201);
    const audit=await db.changeEvent.findFirst({where:{action:'PLANNER_CREATE',kind:'goal',sourceId:saved.body.data.id}});
    assert.equal(audit.after.row.title,'Cadastro auditado');assert.equal(audit.reversible,false);
    const wrongChild=await api('put',`/api/planner/metas/${saved.body.data.id}`).send({title:'Não deve persistir',sessions:[{id:session.id,date,startTime:'12:00',endTime:'13:00',status:'PENDING'}]});
    assert.equal(wrongChild.status,404);
    assert.equal((await db.goal.findUnique({where:{id:saved.body.data.id}})).title,'Cadastro auditado');
    assert.equal((await api('put',`/api/planner/metas/${saved.body.data.id}`).send({title:'Cadastro atualizado',sessions:[]})).status,200);
    const updated=await db.changeEvent.findFirst({where:{action:'PLANNER_UPDATE',sourceId:saved.body.data.id,kind:'goal'}});
    assert.equal(updated.before.row.title,'Cadastro auditado');assert.equal(updated.after.row.title,'Cadastro atualizado');
    assert.equal((await api('post',`/api/productivity/history/${audit.id}/undo`).send({})).status,409);
    assert.equal((await api('delete',`/api/planner/metas/${saved.body.data.id}`)).status,200);
    assert.equal(await db.changeEvent.count({where:{action:'PLANNER_DELETE',sourceId:saved.body.data.id,kind:'goal'}}),1);
    const result=await api('get','/api/productivity/history?limit=2');
    assert.equal(result.status,200);assert.equal(result.body.data.items.length,2);assert.ok(result.body.data.nextCursor);
  });
});
